/// The standard tables from JPEG Annex K as one DHT segment.
static DHT: LazyLock<Vec<u8>> = LazyLock::new(|| {
    let tables: [(u8, &[u8; 16], &[u8]); 4] = [
        (0x00, &DC_LUMA_BITS, &DC_VALUES),
        (0x10, &AC_LUMA_BITS, &AC_LUMA_VALUES),
        (0x01, &DC_CHROMA_BITS, &DC_VALUES),
        (0x11, &AC_CHROMA_BITS, &AC_CHROMA_VALUES),
    ];
    let body: Vec<u8> = tables
        .iter()
        .flat_map(|(class_id, bits, values)| {
            std::iter::once(*class_id)
                .chain(bits.iter().copied())
                .chain(values.iter().copied())
        })
        .collect();
    let len = (body.len() + 2) as u16;
    let mut seg = vec![0xff, 0xc4];
    seg.extend_from_slice(&len.to_be_bytes());
    seg.extend(body);
    seg
});

/// Inserts the standard Huffman tables before the scan if the frame has none.
/// Frames that do not parse are returned unchanged.
pub fn ensure_huffman(mut frame: Vec<u8>) -> Vec<u8> {
    if frame.len() < 4 || frame[0] != 0xff || frame[1] != 0xd8 {
        return frame;
    }
    let mut i = 2;
    while i + 4 <= frame.len() {
        if frame[i] != 0xff {
            return frame;
        }
        match frame[i + 1] {
            0xff => i += 1,
            0xc4 => return frame,
            0xda => {
                frame.splice(i..i, DHT.iter().copied());
                return frame;
            }
            _ => {
                let len = u16::from_be_bytes([frame[i + 2], frame[i + 3]]) as usize;
                i += 2 + len;
            }
        }
    }
    frame
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_sizes_match_their_bit_counts() {
        let sum = |b: &[u8; 16]| b.iter().map(|&x| x as usize).sum::<usize>();
        assert_eq!(sum(&DC_LUMA_BITS), DC_VALUES.len());
        assert_eq!(sum(&DC_CHROMA_BITS), DC_VALUES.len());
        assert_eq!(sum(&AC_LUMA_BITS), AC_LUMA_VALUES.len());
        assert_eq!(sum(&AC_CHROMA_BITS), AC_CHROMA_VALUES.len());
        assert_eq!(DHT.len(), 420);
    }

    #[test]
    fn inserts_tables_before_the_scan() {
        // SOI, APP0 with 2 bytes of payload, SOS, data, EOI
        let frame = vec![
            0xff, 0xd8, 0xff, 0xe0, 0x00, 0x04, 0xaa, 0xbb, 0xff, 0xda, 0x00, 0x02, 0x11, 0xff,
            0xd9,
        ];
        let out = ensure_huffman(frame.clone());
        assert_eq!(out.len(), frame.len() + DHT.len());
        assert_eq!(&out[8..10], &[0xff, 0xc4]);
        assert_eq!(&out[8 + DHT.len()..8 + DHT.len() + 2], &[0xff, 0xda]);
    }

    #[test]
    fn keeps_frames_that_already_have_tables() {
        let frame = vec![0xff, 0xd8, 0xff, 0xc4, 0x00, 0x02, 0xff, 0xda, 0x00, 0x02];
        assert_eq!(ensure_huffman(frame.clone()), frame);
    }

    #[test]
    fn leaves_garbage_alone() {
        assert_eq!(ensure_huffman(vec![1, 2, 3]), vec![1, 2, 3]);
    }
}
